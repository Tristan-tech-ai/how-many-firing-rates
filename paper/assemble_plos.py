"""assemble_plos.py (16 Oct 2026, task P2TEMPLATE): build the PLOS Computational Biology submission file plos/paper2_plos.tex from the
flattened draft paper2_v2_flat.tex (GENERATED by flatten_v2.py; never edit either output).

Template: the official PLOS LaTeX template (data_ext/plos_template/PLOS_latex_template.zip, downloaded 16 Oct 2026 from
journals.plos.org/ploscompbiol/s/latex; files in data_ext/plos_template/unz). Its guidance applied here:
- its preamble (letter paper, wide left margin on the first page, lineno, cite, caption with bold "Fig", fancy footer with page/total);
- title block in flushleft, unnumbered Abstract and Author summary, then \\linenumbers on the body;
- a single .tex file;
- for the initial submission the PDF carries no figures: they are uploaded as separate files, so each figure environment keeps
  its caption at its place in the text and loses its \\includegraphics.
The bibliography stays the draft's thebibliography block; the plos2025.bst style applies only to BibTeX, which the draft does not use.
"""
import io
import os
import re

H = os.path.dirname(os.path.abspath(__file__))
T = os.path.join(H, "..", "data_ext", "plos_template", "unz", "plos_latex_template.tex")
src = io.open(os.path.join(H, "paper2_v2_flat.tex"), encoding="utf-8").read()
tpl = io.open(T, encoding="utf-8").read()

# template preamble: from \documentclass up to (not including) the user macro block
pre = tpl[tpl.index("\\documentclass"):tpl.index("%% Include all user-defined macros below")]
pre = pre.replace("\\bibliographystyle{plos2025}\n", "")
pre = pre.replace("\\usepackage{amsmath,amssymb}", "\\usepackage{amsmath,amssymb,amsthm}\n\\usepackage{url}")

# the draft's own definitions (theorem environments, keyword environment), between \documentclass and \title
dpre = src[:src.index("\\title{")]
own = [l for l in dpre.splitlines() if l.startswith(("\\newtheorem", "\\newenvironment"))]
title = re.search(r"\\title\{(.*?)\}\n", src).group(1)
author = re.search(r"\\author\{([^\\}\n]*)", src).group(1).replace("~", " ")   # the name only; affiliation lines follow (16 Oct)
abstract = src[src.index("\\begin{abstract}") + len("\\begin{abstract}"):src.index("\\end{abstract}")].strip()
body = src[src.index("\\end{abstract}") + len("\\end{abstract}"):src.index("\\end{document}")]

# split the body: author summary and keywords stay before the line numbers; the numbered text starts at the first \section{
k = body.index("\\section{")
front, main = body[:k], body[k:]
n_fig = main.count("\\includegraphics")
main = re.sub(r"\\includegraphics(\[[^\]]*\])?\{[^}]*\}\n?", "", main)
assert "\\includegraphics" not in main and n_fig == 3, n_fig
main = main.replace("\\begin{figure}[!ht]", "\\begin{figure}[!h]")

head = (pre + "\n".join(own) + "\n\n\\begin{document}\n\\vspace*{0.2in}\n\n\\begin{flushleft}\n{\\Large\n\\textbf{" + title + "}\n}\n"
        "\\newline\n\\\\\n" + author + "\\textsuperscript{1*}\n\\\\\n\\bigskip\n"
        "\\textbf{1} Independent Researcher, Bali, Indonesia\n\\\\\n\\bigskip\n\n"
        "* madetristanfirdaus@gmail.com\n\\end{flushleft}\n\n\\section*{Abstract}\n" + abstract + "\n")
out = head + front + "\n\\clearpage\n\\newgeometry{top=0.85in,left=1in,right=1in,footskip=0.75in}\n\\linenumbers\n\n" + main + \
      "\n\\nolinenumbers\n\\end{document}\n"
# 16 Oct 2026 (P2REPOLOG step 3): the submission file carries no working comments
out = "\n".join(l for l in (re.sub(r"(?<!\\)%.*$", "%", x) if re.search(r"(?<!\\)%", x) and x[:re.search(r"(?<!\\)%", x).start()].strip() else (None if re.search(r"(?<!\\)%", x) else x) for x in out.split("\n")) if l is not None)
os.makedirs(os.path.join(H, "plos"), exist_ok=True)
io.open(os.path.join(H, "plos", "paper2_plos.tex"), "w", encoding="utf-8", newline="\n").write(
    out)
print("written plos/paper2_plos.tex; figures removed:", n_fig)
