"""
Interval-arithmetic evaluation of D and its derivatives to order six, for PROVED bounds. 2026-09-06.

Why. The certificate (q32_certificate_v2.py) is an inequality argument whose constants M2 = max|D''| and
M3 = max|D'''| on each subinterval are sampled maxima, which the independent audit flagged and Amendment 68 states as
the remaining limit. mpmath's iv context evaluates every operation with directed rounding, so an expression
evaluated on an interval X returns an interval containing the value at every x in X.

Closed forms. With L(x,y) = y log x - x - log y!, P = exp L, g = L - log Q(y), u = y/x:
    D^(n)(x) = sum_y P(x,y) h_n(u, x) g(x,y) + c_n(x),
    h_0 = 1,  h_{n+1} = dh_n/dx + h_n (u - 1),  c_{n+1} = E_x[h_n (U - 1)] + dc_n/dx  (U ~ Poisson(x)).
The first three are the ones used since support_mp3 (h_1 = u - 1, h_2 = (u-1)^2 - u/x, c_2 = 1/x). The
recurrence was run symbolically (sympy, Touchard moments E[Y^k] = sum_j S(k,j) x^j for the expectation) and
the resulting coefficient tables are hard-coded below as h_n = sum coef u^i / x^j; the control block
regenerates them from the recurrence and compares, and checks each closed form against a central difference
of the previous one. Those are the computations that could refute the tables. c_n = (-1)^n (n-2)!/x^(n-1).

Enclosures. The naive interval sum over-estimates the range by an amount LINEAR in the width h (0.29 h for
D'' at x = 20). The centered form  f(X) subset f(m) + f'(X) [-h/2, h/2]  is rigorous by the mean-value theorem
and over-estimates at order h^2; applied recursively to depth k it over-estimates at order h^(k+1), at the
cost of k + 1 sums and the closed form k orders higher. The first proved certificate (depth 1) failed at A = 100
by 1e-8 on five gaps because M3 at the flat atoms was over-estimated 20 to 500 times; depth 2 to 3 is what the
flat atoms need, which is why the tables go to order six.

What is and is not rigorous. Everything downstream of the decimal input (x_k, w_k as decimal strings) is
interval-enclosed: P and Q, log Q, log y!, every derivative; the y-sum truncation is bounded by tail_bound().
What this module does NOT make rigorous is the step from the decimal input, which satisfies the KKT
equalities only to its own residual (5e-16 for inputs stored as 17-digit floats), to an exact KKT point;
that is the audit's caveat 1 and the certificate reports it as the number eta rather than hiding it.
"""

