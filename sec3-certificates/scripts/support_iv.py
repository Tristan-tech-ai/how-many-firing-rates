# c_n = coef / x^j
CC = {0: [], 1: [], 2: [(1, 1)], 3: [(-1, 2)], 4: [(2, 3)], 5: [(-6, 4)], 6: [(24, 5)]}
MAXORDER = 6


def _poly(order, u, xinv):
    """h_order(u, x) from the table; u and xinv may be intervals or mpf"""
    up = [1]
    xp = [1]
    for _ in range(order):
        up.append(up[-1] * u)
    for _ in range(order):
        xp.append(xp[-1] * xinv)
    s = 0
    for coef, i, j in H[order]:
        s = s + coef * up[i] * xp[j]
    return s


def _const(order, xinv):
    s = 0
    for coef, j in CC[order]:
        s = s + coef * xinv**j
    return s


class Channel:
    def __init__(self, A, xs, ws, dps=40, extra_ny=0):
        mp.dps = dps
        iv.dps = dps
        self.A = mpf(A)
        self.ny = int(float(A) + 18 * float(A) ** 0.5 + 50) + extra_ny
        self.LF = [iv.loggamma(iv.mpf(y + 1)) for y in range(self.ny)]
        self.LFp = [loggamma(y + 1) for y in range(self.ny)]

        # parameters may be decimal strings / floats (degenerate intervals) or intervals (a box around a
        # numerical KKT point, for the exact-point certificate); midpoints serve the sampling grids
        def as_iv(v):
            return (
                v
                if hasattr(v, "a") and hasattr(v, "b")
                else iv.mpf(v if isinstance(v, str) else repr(float(v)))
            )

        self.x = [as_iv(v) for v in xs]
        w = [as_iv(v) for v in ws]
        t = w[0]
        for v in w[1:]:
            t = t + v
        self.w = [v / t for v in w]
        self.K = len(xs)
        self.Q = []
        for y in range(self.ny):
            q = iv.mpf(0)
            for k in range(self.K):
                if self.x[k].a <= 0:
                    if y == 0:
                        q = q + self.w[k]
                else:
                    q = q + self.w[k] * self.P(self.x[k], y)
            self.Q.append(q)
        self.logQ = [iv.log(q) for q in self.Q]
        self.xp = [(mpf(v.a) + mpf(v.b)) / 2 for v in self.x]
        wp = [(mpf(v.a) + mpf(v.b)) / 2 for v in w]
        tp = sum(wp)
        self.wp = [v / tp for v in wp]
        self.Qp = [q.mid for q in self.Q]
        self.logQp = [log(q) for q in self.Qp]

    # ---- interval evaluation ----
    def L(self, X, y):
        return y * iv.log(X) - X - self.LF[y]

    def P(self, X, y):
        return iv.exp(self.L(X, y))

    def _sum(self, X, order):
        """naive interval enclosure of D^(order) over X"""
        if X.a <= 0:
            if X.a == X.b == 0 and order == 0:
                return -self.logQ[0]  # D(0) = -log Q(0), exactly
            raise ValueError("interval touches 0")
        xinv = 1 / X
        lX = iv.log(X)
        s = iv.mpf(0)
        for y in range(self.ny):
            Lv = y * lX - X - self.LF[y]
            p = iv.exp(Lv)
            g = Lv - self.logQ[y]
            s = s + p * _poly(order, y * xinv, xinv) * g
        return s + _const(order, xinv)

    def enclose(self, X, order, depth=2):
        """rigorous enclosure of D^(order) over X by the mean-value form applied recursively to the given depth"""
        if depth <= 0 or order + 1 > MAXORDER:
            return self._sum(X, order)
        a, b = mpf(X.a), mpf(X.b)
        if a == b:
            return self._sum(X, order)
        m = (a + b) / 2
        half = (b - a) / 2
        return self._sum(iv.mpf(m), order) + self.enclose(X, order + 1, depth - 1) * mpi(-half, half)

    def absmax(self, lo, hi, order, pieces=1, depth=2):
        """proved bound on max |D^(order)| over [lo, hi]"""
        best = mpf(0)
        for j in range(pieces):
            a = lo + (hi - lo) * mpf(j) / pieces
            b = lo + (hi - lo) * mpf(j + 1) / pieces
            v = self.enclose(mpi(a, b), order, depth)
            best = max(best, abs(mpf(v.a)), abs(mpf(v.b)))
        return best

    def D_iv(self, X):
        return self._sum(X, 0)

    def Dp_iv(self, X):
        return self._sum(X, 1)

    def Dpp_iv(self, X):
        return self._sum(X, 2)

    def Dppp_iv(self, X):
        return self._sum(X, 3)

    # ---- point evaluation (mpf), same closed forms ----
    def deriv(self, x, order):
        xinv = 1 / x
        lx = log(x)
        s = mpf(0)
        for y in range(self.ny):
            Lv = y * lx - x - self.LFp[y]
            if Lv < -400:
                continue
            s += exp(Lv) * _poly(order, y * xinv, xinv) * (Lv - self.logQp[y])
        return s + _const(order, xinv)

    def D(self, x):
        return self.deriv(x, 0)

    def Dp(self, x):
        return self.deriv(x, 1)

    def Dpp(self, x):
        return self.deriv(x, 2)

    def Dppp(self, x):
        return self.deriv(x, 3)

    def C_iv(self):
        c = iv.mpf(0)
        for k in range(self.K):
            if self.x[k].a <= 0:
                c = c + self.w[k] * (-self.logQ[0])
            else:
                c = c + self.w[k] * self.D_iv(self.x[k])
        return c

    def tail_bound(self, x_lo, order):
        """rigorous bound on the dropped tail sum_{y >= ny} P(x,y) |h_order| |g| for every x in [x_lo, A].
        For y >= ny > A: P(x,y) <= P(A,y), and P(A,y+1)/P(A,y) = A/(y+1) <= rho := A/ny < 1. For such y,
        w_A P(A,y) <= Q(y) <= P(A,y), so g = log P(x,y) - log Q(y) lies in [y log(x_lo/A), A + log(1/w_A)]
        and |g| <= max(A + log(1/w_A), y log(A/x_lo)). |h_order| <= sum |coef| (y/x_lo)^i / x_lo^j from the
        table. Every factor grows by at most (1 + 1/ny) per unit step in y beyond ny, so the summand is bounded
        by its value at ny times a geometric series with ratio rho (1 + 1/ny)^(order + 2)."""
        A = self.A
        ny = self.ny
        x_lo = mpf(x_lo)
        wA = mpf(self.w[-1].a)  # lower end, so the bound holds for every input in the box
        rho = A / ny
        rho2 = rho * (1 + mpf(1) / ny) ** (order + 2)
        if rho2 >= 1:
            return None
        PA = exp(ny * log(A) - A - loggamma(ny + 1))
        gb = max(A + log(1 / wA), ny * log(A / x_lo))
        hb = sum(abs(coef) * (ny / x_lo) ** i / x_lo**j for coef, i, j in H[order])
        return PA * hb * gb / (1 - rho2)


